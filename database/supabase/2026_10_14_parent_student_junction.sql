-- Backfill parent/student links into the canonical many-to-many table.
-- Keep parents.student_id during the application rollout for a safe rollback.

create table if not exists public.parents_students (
  id bigint generated by default as identity primary key,
  parent_id bigint not null references public.parents(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  relationship text,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

alter table public.parents_students add column if not exists relationship text;
alter table public.parents_students add column if not exists created_at timestamp with time zone not null default now();
alter table public.parents_students add column if not exists updated_at timestamp with time zone not null default now();

do $$
declare
  identity_generation "char";
  sequence_name text;
  max_id bigint;
begin
  select a.attidentity
  into identity_generation
  from pg_attribute a
  where a.attrelid = 'public.parents_students'::regclass
    and a.attname = 'id'
    and not a.attisdropped;

  if identity_generation = '' and pg_get_serial_sequence('public.parents_students', 'id') is null then
    alter table public.parents_students
      alter column id add generated by default as identity;
  end if;

  sequence_name := pg_get_serial_sequence('public.parents_students', 'id');
  if sequence_name is not null then
    select max(id) into max_id from public.parents_students;
    if max_id is null then
      perform setval(sequence_name::regclass, 1, false);
    else
      perform setval(sequence_name::regclass, max_id, true);
    end if;
  end if;
end
$$;

with ranked_links as (
  select ctid, row_number() over (partition by parent_id, student_id order by id) as duplicate_number
  from public.parents_students
)
delete from public.parents_students ps
using ranked_links rl
where ps.ctid = rl.ctid
  and rl.duplicate_number > 1;

create unique index if not exists parents_students_parent_id_student_id_key
  on public.parents_students (parent_id, student_id);
create index if not exists parents_students_student_id_idx
  on public.parents_students (student_id);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'parents_students_parent_id_fkey'
      and conrelid = 'public.parents_students'::regclass
  ) then
    alter table public.parents_students
      add constraint parents_students_parent_id_fkey
      foreign key (parent_id) references public.parents(id) on delete cascade;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'parents_students_student_id_fkey'
      and conrelid = 'public.parents_students'::regclass
  ) then
    alter table public.parents_students
      add constraint parents_students_student_id_fkey
      foreign key (student_id) references public.students(id) on delete cascade;
  end if;
end
$$;

insert into public.parents_students (parent_id, student_id, relationship)
select p.id, p.student_id, p.relationship
from public.parents p
where p.student_id is not null
  and exists (select 1 from public.students s where s.id = p.student_id)
on conflict (parent_id, student_id) do nothing;

do $$
begin
  if exists (
    select 1
    from public.parents p
    where p.student_id is not null
      and not exists (
        select 1 from public.parents_students ps
        where ps.parent_id = p.id and ps.student_id = p.student_id
      )
  ) then
    raise exception 'Parent-student backfill incomplete; keep parents.student_id and resolve the missing associations before proceeding.';
  end if;
end
$$;
