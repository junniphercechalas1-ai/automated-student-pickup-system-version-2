-- Supabase SQL schema for Automated Student Pickup Verification System
-- For existing databases, first run database/supabase/2026_10_21_rename_student_foreign_keys_to_students_id.sql.

-- 1. students table
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  first_name text not null,
  middle_name text,
  last_name text not null,
  grade_level text,
  section text,
  created_at timestamp with time zone default timezone('utc', now()),
  updated_at timestamp with time zone default timezone('utc', now())
);

alter table public.students add column if not exists first_name text;
alter table public.students add column if not exists middle_name text;
alter table public.students add column if not exists last_name text;
alter table public.students add column if not exists grade_level text;
alter table public.students add column if not exists section text;

alter table public.students drop column if exists name;
alter table public.students drop column if exists class;
alter table public.students drop column if exists qr_code;

-- 2. pickups table
create table if not exists public.pickups (
  id bigint generated by default as identity primary key,
  students_id bigint not null references public.students(id) on delete cascade,
  parents_id bigint,
  picked_at timestamp with time zone not null,
  created_at timestamp with time zone default timezone('utc', now())
);

-- 3. parents table (optional if you want parent profiles)
create table if not exists public.parents (
  id bigint generated by default as identity primary key,
  auth_users_id uuid unique references auth.users(id) on delete cascade,
  first_name text not null,
  middle_name text,
  last_name text not null,
  relationship text not null,
  mobile_number text not null,
  email text,
  created_at timestamp with time zone default timezone('utc', now()),
  updated_at timestamp with time zone default timezone('utc', now())
);

create table if not exists public.parents_students (
  id bigint generated by default as identity primary key,
  parents_id bigint not null references public.parents(id) on delete cascade,
  students_id bigint not null references public.students(id) on delete cascade,
  relationship text,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint parents_students_parents_id_students_id_key unique (parents_id, students_id)
);

create index if not exists parents_students_students_id_idx
  on public.parents_students (students_id);

alter table public.parents add column if not exists auth_users_id uuid;
alter table public.parents drop constraint if exists parents_auth_users_id_fkey;
alter table public.parents
  add constraint parents_auth_users_id_fkey
  foreign key (auth_users_id) references auth.users(id) on delete cascade;
create unique index if not exists idx_parents_auth_users_id
  on public.parents (auth_users_id)
  where auth_users_id is not null;

alter table public.pickups add column if not exists parents_id bigint;
alter table public.pickups drop constraint if exists pickups_parents_id_fkey;
alter table public.pickups
  add constraint pickups_parents_id_fkey
  foreign key (parents_id) references public.parents(id) on delete set null;

alter table public.parents add column if not exists email text;
alter table public.parents add column if not exists is_approved boolean default false;
create unique index if not exists idx_parents_email_unique
  on public.parents (lower(email))
  where email is not null;
create index if not exists idx_parents_is_approved
  on public.parents (is_approved);

-- 4. staff table for staff access / approvals
create table if not exists public.staff (
  id uuid primary key references auth.users(id) on delete cascade,
  auth_users_id uuid references auth.users(id) on delete cascade,
  first_name text,
  middle_name text,
  last_name text,
  email text not null unique,
  phone_number text,
  photo_url text,
  is_approved boolean default false,
  created_at timestamptz default now()
);

alter table public.staff alter column email drop not null;
alter table public.staff
  add column if not exists auth_users_id uuid references auth.users(id) on delete cascade;
update public.staff as staff_profile
set auth_users_id = auth_user.id
from auth.users as auth_user
where staff_profile.auth_users_id is null
  and staff_profile.id = auth_user.id;

create index if not exists idx_staff_email
  on public.staff (email);
create unique index if not exists idx_staff_auth_users_id
  on public.staff (auth_users_id)
  where auth_users_id is not null;

-- Optional RLS setup for the staff table
alter table public.staff enable row level security;

create policy "staff can view own record"
on public.staff
for select
using (auth.uid() = auth_users_id);

create policy "service role can manage staff"
on public.staff
for all
using (true)
with check (true);

-- 7. admin table for system administrators
create table if not exists public.admin (
  id uuid primary key default gen_random_uuid(),
  auth_users_id uuid references auth.users(id) on delete cascade,
  username text unique,
  first_name text,
  middle_name text,
  last_name text,
  email text not null unique,
  phone_number text unique,
  password_hash text not null,
  is_active boolean default true
);

alter table public.admin
  add column if not exists auth_users_id uuid references auth.users(id) on delete cascade,
  add column if not exists username text;
create unique index if not exists idx_admin_auth_users_id
  on public.admin (auth_users_id)
  where auth_users_id is not null;
create unique index if not exists idx_admin_username
  on public.admin (lower(username))
  where username is not null;
create index if not exists idx_admin_email
  on public.admin (email);
create unique index if not exists idx_admin_phone_number_unique
  on public.admin (phone_number)
  where phone_number is not null;

alter table public.admin add column if not exists phone_number text;

-- 8. Add role and status fields to existing tables for better management
alter table public.parents add column if not exists is_active boolean default true;

alter table public.staff add column if not exists role text default 'staff'; -- staff, supervisor
alter table public.staff add column if not exists is_active boolean default true;
alter table public.staff alter column is_approved set default false;

-- RLS for admin table
alter table public.admin enable row level security;

create policy "admin can manage own record"
on public.admin
for select
using (auth.uid() = id);

create policy "service role can manage admin"
on public.admin
for all
using (true)
with check (true);
